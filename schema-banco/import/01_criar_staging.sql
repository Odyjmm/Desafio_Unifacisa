create or replace function importacao.norm(t text)
returns text language sql stable as $$
    select lower(extensions.unaccent('extensions.unaccent'::regdictionary,
           btrim(regexp_replace(coalesce(t, ''), '\s+', ' ', 'g'))))
$$;

create or replace function importacao.cnpj_valido(c text)
returns boolean language plpgsql immutable as $$
declare
    p1 int[] := array[5,4,3,2,9,8,7,6,5,4,3,2];
    p2 int[] := array[6,5,4,3,2,9,8,7,6,5,4,3,2];
    soma int; r int;
begin
    if c is null or c !~ '^[0-9]{14}$' or c ~ '^(.)\1{13}$' then
        return false;
    end if;
    soma := 0;
    for i in 1..12 loop soma := soma + substr(c, i, 1)::int * p1[i]; end loop;
    r := soma % 11; r := case when r < 2 then 0 else 11 - r end;
    if r <> substr(c, 13, 1)::int then return false; end if;
    soma := 0;
    for i in 1..13 loop soma := soma + substr(c, i, 1)::int * p2[i]; end loop;
    r := soma % 11; r := case when r < 2 then 0 else 11 - r end;
    return r = substr(c, 14, 1)::int;
end
$$;

create or replace function importacao.cnae_digitos(t text)
returns text language sql immutable as $$
    select case when m is null then null
                else m[1] || m[2] || coalesce(m[3], '') end
    from (select regexp_match(
              regexp_replace(btrim(coalesce(t, '')), '^([0-9]{2})\.([0-9]{2})', '\1\2'),
              '^([0-9]{4})-?([0-9])(?:[/-]?([0-9]{2}))?(?:\s*[-–—]\s*.*)?$') as m) x
$$;

create or replace function importacao.cnae_descricao(t text)
returns text language sql immutable as $$
    select nullif(btrim(m[4]), '')
    from (select regexp_match(
              regexp_replace(btrim(coalesce(t, '')), '^([0-9]{2})\.([0-9]{2})', '\1\2'),
              '^([0-9]{4})-?([0-9])(?:[/-]?([0-9]{2}))?(?:\s*[-–—]\s*(.*))?$') as m) x
$$;

create or replace view importacao.v_parsed as
with base as (
    select
        s.linha,
        s.id                                                            as id_origem,
        nullif(btrim(regexp_replace(coalesce(s.nome_instituicao, ''), '\s+', ' ', 'g')), '') as razao_social,
        nullif(btrim(regexp_replace(coalesce(s.nome_fantasia, ''), '\s+', ' ', 'g')), '') as nome_fantasia,
        nullif(regexp_replace(coalesce(s.cnpj, ''), '[^0-9]', '', 'g'), '') as cnpj,
        nullif(btrim(s.natureza_juridica), '')                          as natureza_txt,
        nullif(btrim(s.area_atuacao), '')                               as area_txt,
        nullif(btrim(s.municipio), '')                                  as municipio_txt,
        nullif(btrim(regexp_replace(coalesce(s.bairro, ''), '\s+', ' ', 'g')), '') as bairro_txt,
        nullif(btrim(s.publico_alvo), '')                               as publico_txt,
        nullif(btrim(s.ano_criacao), '')                                as ano_txt,
        nullif(btrim(s.telefone_1), '')                                 as telefone_1,
        nullif(btrim(s.telefone_2), '')                                 as telefone_2,
        nullif(lower(btrim(s.email)), '')                               as email,
        nullif(btrim(regexp_replace(coalesce(s.responsavel, ''), '\s+', ' ', 'g')), '') as responsavel,
        nullif(btrim(s.instagram), '')                                  as instagram_txt,
        nullif(btrim(s.facebook), '')                                   as facebook_txt,
        nullif(btrim(s.site), '')                                       as site_txt,
        nullif(btrim(regexp_replace(coalesce(s.endereco_completo, ''), '\s+', ' ', 'g')), '') as endereco_completo,
        nullif(regexp_replace(coalesce(s.cep, ''), '[^0-9]', '', 'g'), '') as cep,
        replace(nullif(btrim(s.latitude), ''), ',', '.')                as lat_txt,
        replace(nullif(btrim(s.longitude), ''), ',', '.')               as lon_txt,
        nullif(btrim(s.cnae_primaria), '')                              as cnae_prim_txt,
        nullif(btrim(s.cnae_secundarias), '')                           as cnae_sec_txt
    from importacao.staging_organizacoes s
)
select
    b.*,
    n.id  as natureza_juridica_id,
    a.id  as area_atuacao_id,
    m.id  as municipio_id,
    case when b.ano_txt ~ '^[0-9]{4}$' then b.ano_txt::smallint end                       as ano_criacao,
    case when b.lat_txt ~ '^-?[0-9]+(\.[0-9]+)?$' then b.lat_txt::numeric end             as latitude,
    case when b.lon_txt ~ '^-?[0-9]+(\.[0-9]+)?$' then b.lon_txt::numeric end             as longitude,
    -- Redes e site viram links completos (o CSV traz "@usuario" e endereços sem https://)
    case when b.instagram_txt is null then null
         when b.instagram_txt ~* '^https?://' then b.instagram_txt
         when b.instagram_txt ~* 'instagram\.com' then 'https://' || b.instagram_txt
         else 'https://www.instagram.com/' || regexp_replace(b.instagram_txt, '^@', '') end as instagram,
    case when b.facebook_txt is null then null
         when b.facebook_txt ~* '^https?://' then b.facebook_txt
         when b.facebook_txt ~* '(facebook|fb)\.com' then 'https://' || b.facebook_txt
         else 'https://www.facebook.com/' || regexp_replace(b.facebook_txt, '^@', '') end as facebook,
    case when b.site_txt is null then null
         when b.site_txt ~* '^https?://' then b.site_txt
         else 'https://' || b.site_txt end                                                as site
from base b
left join public.naturezas_juridicas n on importacao.norm(n.descricao) = importacao.norm(b.natureza_txt)
left join public.areas_atuacao       a on importacao.norm(a.nome)      = importacao.norm(b.area_txt)
left join public.municipios          m on importacao.norm(m.nome)      = importacao.norm(b.municipio_txt) and m.uf = 'PB';

create or replace view importacao.v_problemas as

select linha, 'ERRO' as severidade, 'nome_instituicao' as campo, 'Nome da instituição vazio' as mensagem, null::text as valor
  from importacao.v_parsed where razao_social is null
union all
select linha, 'ERRO', 'cnpj', 'CNPJ precisa ter 14 dígitos', cnpj
  from importacao.v_parsed where cnpj is not null and cnpj !~ '^[0-9]{14}$'
union all
select linha, 'ERRO', 'cnpj', 'CNPJ com dígitos verificadores inválidos (provável erro de digitação)', cnpj
  from importacao.v_parsed where cnpj ~ '^[0-9]{14}$' and not importacao.cnpj_valido(cnpj)
union all
select linha, 'ERRO', 'cnpj', 'CNPJ repetido dentro do CSV', cnpj
  from importacao.v_parsed
 where cnpj in (select cnpj from importacao.v_parsed where cnpj is not null group by cnpj having count(*) > 1)
union all
select p.linha, 'ERRO', 'cnpj', 'CNPJ já existe no banco', p.cnpj
  from importacao.v_parsed p join public.organizacoes o on o.cnpj = p.cnpj
union all
select linha, 'AVISO', 'cnpj', 'Sem CNPJ: a organização não poderá usar o fluxo de edição por CNPJ', null
  from importacao.v_parsed where cnpj is null
union all
select a.linha, 'AVISO', 'cnpj', 'Mesma raiz de CNPJ (matriz/filial) de outra linha: confira se não é a mesma entidade', a.cnpj
  from importacao.v_parsed a
 where a.cnpj ~ '^[0-9]{14}$'
   and exists (select 1 from importacao.v_parsed b
                where b.linha <> a.linha and b.cnpj ~ '^[0-9]{14}$'
                  and left(b.cnpj, 8) = left(a.cnpj, 8) and b.cnpj <> a.cnpj)
union all
select linha, 'ERRO', 'natureza_juridica', 'Valor fora da lista de naturezas jurídicas', natureza_txt
  from importacao.v_parsed where natureza_txt is not null and natureza_juridica_id is null
union all
select linha, 'AVISO', 'natureza_juridica', 'Natureza jurídica vazia', null
  from importacao.v_parsed where natureza_txt is null
union all
select linha, 'ERRO', 'area_atuacao', 'Valor fora da lista de áreas de atuação', area_txt
  from importacao.v_parsed where area_txt is not null and area_atuacao_id is null
union all
select linha, 'AVISO', 'area_atuacao', 'Área de atuação vazia', null
  from importacao.v_parsed where area_txt is null
union all
select linha, 'ERRO', 'municipio', 'Município vazio', null
  from importacao.v_parsed where municipio_txt is null
union all
select linha, 'ERRO', 'municipio', 'Município fora da lista da RMCG', municipio_txt
  from importacao.v_parsed where municipio_txt is not null and municipio_id is null
union all
select p.linha, 'ERRO', 'publico_alvo', 'Público-alvo fora da lista', t.item
  from importacao.v_parsed p
  cross join lateral regexp_split_to_table(coalesce(p.publico_txt, ''), '\s*\|\s*') as t(item)
 where btrim(t.item) <> ''
   and not exists (select 1 from public.publicos_alvo pa where importacao.norm(pa.nome) = importacao.norm(t.item))
union all
select linha, 'AVISO', 'publico_alvo', 'Público-alvo vazio', null
  from importacao.v_parsed where publico_txt is null
union all
select linha, 'ERRO', 'ano_criacao', 'Ano precisa ter 4 dígitos entre 1500 e 2100', ano_txt
  from importacao.v_parsed
 where ano_txt is not null and (ano_txt !~ '^[0-9]{4}$' or ano_txt::int not between 1500 and 2100)
union all
select linha, 'ERRO', 'cep', 'CEP precisa ter 8 dígitos', cep
  from importacao.v_parsed where cep is not null and cep !~ '^[0-9]{8}$'
union all
select linha, 'ERRO', 'email', 'E-mail em formato inválido', email
  from importacao.v_parsed where email is not null and email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'
union all
select linha, 'ERRO', 'latitude', 'Latitude não é um número (use ponto decimal)', lat_txt
  from importacao.v_parsed where lat_txt is not null and latitude is null
union all
select linha, 'ERRO', 'longitude', 'Longitude não é um número (use ponto decimal)', lon_txt
  from importacao.v_parsed where lon_txt is not null and longitude is null
union all
select linha, 'ERRO', 'latitude/longitude', 'Informe latitude e longitude juntas, ou nenhuma das duas', coalesce(lat_txt, '') || ' / ' || coalesce(lon_txt, '')
  from importacao.v_parsed where (lat_txt is null) <> (lon_txt is null)
union all
select linha, 'ERRO', 'latitude/longitude', 'Coordenada fora do intervalo válido', lat_txt || ' / ' || lon_txt
  from importacao.v_parsed
 where latitude is not null and longitude is not null
   and (latitude not between -90 and 90 or longitude not between -180 and 180)
union all
select linha, 'AVISO', 'latitude/longitude', 'Coordenada fora da região esperada (confira sinal ou troca de latitude e longitude)', lat_txt || ' / ' || lon_txt
  from importacao.v_parsed
 where latitude between -90 and 90 and longitude between -180 and 180
   and not (latitude between -8.3 and -6.5 and longitude between -37.2 and -34.8)
union all
select linha, 'AVISO', 'latitude/longitude', 'Sem coordenadas: a organização não aparecerá no mapa', null
  from importacao.v_parsed where lat_txt is null and lon_txt is null
union all
select linha, 'ERRO', 'cnae_primaria', 'CNAE em formato não reconhecido', cnae_prim_txt
  from importacao.v_parsed where cnae_prim_txt is not null and importacao.cnae_digitos(cnae_prim_txt) is null
union all
select linha, 'AVISO', 'cnae_primaria', 'CNAE primária vazia', null
  from importacao.v_parsed where cnae_prim_txt is null
union all
select p.linha, 'ERRO', 'cnae_secundarias', 'CNAE em formato não reconhecido', t.item
  from importacao.v_parsed p
  cross join lateral regexp_split_to_table(coalesce(p.cnae_sec_txt, ''), '\s*\|\s*') as t(item)
 where btrim(t.item) <> '' and importacao.cnae_digitos(t.item) is null;